<#
  Builds a clean copy of the project ready to push to GitHub.

    .\make-release.ps1                    # public-safe: WITHOUT the commercial Vuexy files
    .\make-release.ps1 -IncludeVuexy      # private repo only: keeps the built Vuexy files
    .\make-release.ps1 -Output D:\out\SmartMedicalID

  If the output folder is already a git repository, its .git history is kept and only the
  files are replaced; then review with `git status` and commit/push from that folder.

  Never copied: virtual env, database + backups, uploaded medical files, push private key,
  caches, load-test results, local secrets (.env), the private study guide.
#>
param(
    [string]$Output = (Join-Path (Split-Path $PSScriptRoot -Parent) 'release\SmartMedicalID'),
    [switch]$IncludeVuexy
)
$ErrorActionPreference = 'Stop'
$src = $PSScriptRoot

if (Test-Path $Output) {
    # keep the repository history; replace everything else
    Get-ChildItem $Output -Force | Where-Object { $_.Name -ne '.git' } | Remove-Item -Recurse -Force
}
New-Item -ItemType Directory -Force $Output | Out-Null

$excludeDirs = @('.venv', 'venv', '__pycache__', 'node_modules', '.git', '.idea', '.vscode',
                 (Join-Path $src 'backend\media'), (Join-Path $src 'backend\backups'),
                 (Join-Path $src 'backend\staticfiles'), (Join-Path $src 'loadtest\results'))
if (-not $IncludeVuexy) { $excludeDirs += (Join-Path $src 'frontend\assets\vendor') }
$excludeFiles = @('db.sqlite3', 'db.sqlite3-*', 'vapid_private.pem', '.env', '*.pyc', '*.log', 'make-release.ps1',
                  'دليل-الطالب*', 'مرجعي-الشخصي*')   # private guides stay local

robocopy $src $Output /E /XD $excludeDirs /XF $excludeFiles /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
Copy-Item (Join-Path $src 'make-release.ps1') $Output   # keep the script itself in the release

if (-not $IncludeVuexy) {
    $vendor = Join-Path $Output 'frontend\assets\vendor'
    New-Item -ItemType Directory -Force $vendor | Out-Null
    Set-Content -Encoding utf8 (Join-Path $vendor 'README.md') @'
# Vuexy theme files (not included)

The UI is built on the commercial **Vuexy** Bootstrap admin template, whose licence does not allow
redistributing its files. With your own licensed copy of the template, generate this folder:

```powershell
node frontend/tools/build-theme.js "<path-to-your-Vuexy-template>"
```

The script re-colours the theme to the project's brand teal, minifies it, and writes the 24 files
the app uses into this folder (`frontend/assets/vendor/`).
'@
    Add-Content -Encoding utf8 (Join-Path $Output '.gitignore') "`n# Commercial Vuexy theme files (generated by frontend/tools/build-theme.js)`nfrontend/assets/vendor/*`n!frontend/assets/vendor/README.md"
}

$files = Get-ChildItem $Output -Recurse -File -Force
"Release ready: $Output"
"  files: $($files.Count), size: {0:N1} MB" -f (($files | Measure-Object Length -Sum).Sum / 1MB)
"  Vuexy files: $(if ($IncludeVuexy) { 'INCLUDED - push to a PRIVATE repository only' } else { 'excluded (public-safe)' })"

exit 0
